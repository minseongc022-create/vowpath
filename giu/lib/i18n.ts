export type GiuI18nKey = keyof typeof KO;

export function t(_locale: GiuLocale, key: GiuI18nKey): string {
  return KO[key] ?? String(key);
}

export function chatOpenLabel(locale: GiuLocale, role: "customer" | "merchant"): string {
  return t(locale, role === "merchant" ? "chatOpenMerchant" : "chatOpenCustomer");
}

export function chatTitleLabel(locale: GiuLocale, role: "customer" | "merchant"): string {
  return t(locale, role === "merchant" ? "chatTitleMerchant" : "chatTitleCustomer");
}

export function chatCallLabel(locale: GiuLocale, role: "customer" | "merchant"): string {
  return t(locale, role === "merchant" ? "chatCallMerchant" : "chatCallCustomer");
}

export function chatEmptyLabel(locale: GiuLocale, role: "customer" | "merchant"): string {
  return t(locale, role === "merchant" ? "chatEmptyMerchant" : "chatEmptyCustomer");
}

export function welcomeMessage(
  locale: GiuLocale,
  role: "customer" | "merchant",
  name: string,
): string {
  const key = role === "merchant" ? "welcomeMerchant" : "welcomeCustomer";
  return t(locale, key).replace("{name}", name);
}

