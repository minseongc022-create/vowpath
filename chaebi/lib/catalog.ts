import { NATIONWIDE, regionLabel } from "./regions";

/**
 * 시범 카탈로그.
 *
 * ★ 여기 있는 상호·상품은 전부 가상이다. 실제 업체 정보를 흉내 내지 않는다.
 *
 * 진짜 서비스에서는 이 자리에 제휴사 API(예약·주문·재고)가 들어온다. 그래서
 * 카탈로그는 "엔진이 무엇을 알아야 하는가"의 명세 역할을 겸한다 — 가격,
 * 준비에 걸리는 시간(leadTimeHours), 주문 마감(orderCutoff), 예약 가능
 * 시간대(slots), 취소 규정. 이 필드들이 있어야 "오늘 저녁 7시"라는 말에서
 * 무엇이 가능하고 무엇이 이미 늦었는지를 계산할 수 있다.
 *
 * 카탈로그가 실 데이터로 바뀌어도 아래 CatalogItem 모양만 지키면 엔진·화면은
 * 손댈 필요가 없다.
 */

const DINNER_SLOTS = ["17:00", "17:30", "18:00", "18:30", "19:00", "19:30", "20:00", "20:30"];
const LUNCH_SLOTS = ["11:30", "12:00", "12:30", "13:00", "13:30"];
const ALL_DAY_SLOTS = [...LUNCH_SLOTS, "14:00", "15:00", "16:00", ...DINNER_SLOTS];
const ACTIVITY_SLOTS = ["11:00", "13:00", "15:00", "17:00", "19:00", "21:00"];

type RestaurantRow = [
  id: string,
  name: string,
  category: string,
  priceKrw: number,
  rating: number,
  reviews: number,
  tags: string,
  highlight: string,
  addressHint: string,
];

type ShopRow = [
  id: string,
  name: string,
  category: string,
  priceKrw: number,
  rating: number,
  reviews: number,
  tags: string,
  highlight: string,
  addressHint: string,
  leadTimeHours: number,
];

type GiftRow = [
  id: string,
  name: string,
  category: string,
  priceKrw: number,
  rating: number,
  reviews: number,
  tags: string,
  highlight: string,
  mode: "delivery" | "instant",
  leadTimeHours: number,
];

function splitTags(tags: string): string[] {
  return tags
    .split(",")
    .map((t) => t.trim())
    .filter(Boolean);
}

function restaurant(regionKey: string, row: RestaurantRow): CatalogItem {
  const [id, name, category, priceKrw, rating, reviewCount, tags, highlight, addressHint] = row;
  return {
    id,
    need: "restaurant",
    name,
    category,
    regionKey,
    regionLabel: regionLabel(regionKey),
    priceKrw,
    perPerson: true,
    rating,
    reviewCount,
    tags: splitTags(tags),
    leadTimeHours: 2,
    fulfillment: "reserve",
    slots: tags.includes("점심") ? ALL_DAY_SLOTS : DINNER_SLOTS,
    highlight,
    cancelPolicy: "방문 4시간 전까지 무료 취소",
    addressHint,
  };
}

function pickupShop(need: NeedKind, regionKey: string, row: ShopRow): CatalogItem {
  const [id, name, category, priceKrw, rating, reviewCount, tags, highlight, addressHint, leadTimeHours] = row;
  return {
    id,
    need,
    name,
    category,
    regionKey,
    regionLabel: regionLabel(regionKey),
    priceKrw,
    perPerson: false,
    rating,
    reviewCount,
    tags: splitTags(tags),
    leadTimeHours,
    fulfillment: "pickup",
    highlight,
    cancelPolicy: "픽업 6시간 전까지 무료 취소",
    addressHint,
  };
}

function activity(regionKey: string, row: RestaurantRow, perPerson = true): CatalogItem {
  const [id, name, category, priceKrw, rating, reviewCount, tags, highlight, addressHint] = row;
  return {
    id,
    need: tags.includes("스냅") ? "photo" : "activity",
    name,
    category,
    regionKey,
    regionLabel: regionLabel(regionKey),
    priceKrw,
    perPerson,
    rating,
    reviewCount,
    tags: splitTags(tags),
    leadTimeHours: tags.includes("스냅") ? 24 : 4,
    fulfillment: "reserve",
    slots: ACTIVITY_SLOTS,
    highlight,
    cancelPolicy: "이용 24시간 전까지 무료 취소",
    addressHint,
  };
}

function gift(row: GiftRow): CatalogItem {
  const [id, name, category, priceKrw, rating, reviewCount, tags, highlight, mode, leadTimeHours] = row;
  return {
    id,
    need: "gift",
    name,
    category,
    regionKey: NATIONWIDE,
    regionLabel: "전국 배송",
    priceKrw,
    perPerson: false,
    rating,
    reviewCount,
    tags: splitTags(tags),
    leadTimeHours,
    fulfillment: mode === "instant" ? "instant" : "delivery",
    highlight,
    cancelPolicy: mode === "instant" ? "미사용 시 90일 내 환불" : "배송 시작 전 무료 취소",
    addressHint: mode === "instant" ? "카카오톡·문자로 즉시 전송" : "전국 택배 (당일 15시 이전 주문 시 익일 도착)",
    orderCutoff: mode === "instant" ? undefined : "15:00",
  };
}

function delivered(need: NeedKind, row: GiftRow): CatalogItem {
  return { ...gift(row), need };
}

