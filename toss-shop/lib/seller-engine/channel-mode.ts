/**
 * 판매 채널 모드 — 지금은 토스쇼핑 위탁 전용
 *
 * ★ 왜 수입판매를 껐는가 (전략 판단):
 *
 * 토스 배송 품질 우수 인센티브의 4조건(페널티 0 · 오늘출발 · 7영업일 발송이력 ·
 * 발송기한 준수율 100%)에는 **자체 재고 요건이 없다.** 공급처가 당일 출고만
 * 해주면 위탁으로도 판매수수료 0%를 그대로 받는다. 그러면 같은 8%를
 * 자본 리스크 없이 먹을 수 있으므로, 수입(선매입)이 위탁보다 나을
 * 구조적 이유가 사라진다.
 *
 * 게다가 수입은 틀리면 재고가 그대로 손실이라 시행착오 비용이 다르다.
 * 위탁은 틀려도 손실이 0이라 계속 시도할 수 있다.
 *
 * ★ 왜 코드를 지우지 않고 격리하는가:
 * 위탁으로 도저히 카탈로그를 못 뚫는 품목이 쌓이면 수입이 다시 카드가 된다.
 * 그때 되살릴 수 있게 코드는 남기되, **가짜 숫자가 셀러에게 보이지 않도록**
 * 차단한다.
 *
 * ⚠️ 격리해야 하는 진짜 이유 — import-sources.ts는 원가를 이렇게 만든다:
 *     const h = hashString(keyword + "cn");
 *     const ratio = 0.18 + (h % 8) / 100;
 * **키워드 문자열 해시로 공급가를 생성한다.** 상품과 아무 관계가 없다.
 * 그 위에 마진이 소수점 한 자리까지 계산되고, 랜딩코스트에는 부가세 10%가
 * 통째로 빠져 있으며(관세만 8% 고정), 관세 과표도 CIF가 아니라 FOB다.
 * 즉 표시되는 마진은 실제보다 최소 15~20%p 낙관적이다.
 *
 * 이 숫자를 근거로 실제 발주를 하면 돈을 잃는다. 그래서 기본값은 OFF다.
 */

export const CHANNEL_MODE_VERSION = "1.0";

/**
 * 수입판매 활성화 여부.
 *
 * 기본 false. 되살리려면 랜딩코스트를 실측으로 바꾸는 것이 선행되어야 한다:
 *   CIF = FOB + 국제운임 + 보험
 *   관세 = CIF × 관세율(HS코드별)
 *   부가세 = (CIF + 관세) × 10%
 * 그리고 KC·식약처·전파 인증 게이트가 있어야 한다. 그 전에 켜는 것은
 * 추정치로 재고를 사는 것과 같다.
 */
export function isImportSalesEnabled(): boolean {
  return process.env.TOSS_SHOP_IMPORT_SALES_ENABLED?.trim().toLowerCase() === "true";
}

/** 지금 이 시스템이 파는 방식 — UI·브리프 문구에 쓴다 */
export function activeChannelLabel(): string {
  return isImportSalesEnabled()
    ? "토스쇼핑 위탁 + 수입판매(실험)"
    : "토스쇼핑 위탁 전용";
}

